#!/usr/bin/env python3
"""backup_dataset_schema.py — Sanitize a Domo dataset schema into a safe local mirror.

これは `skills/domo-config-backup.md` の「データセットはスキーマのみ（列名＋型）を
ミラーし、行データ・プレビュー・所有者などは絶対に持ち込まない」ゲートを、
再利用可能・単体テスト可能な形で実装したもの。

設計方針（なぜこの形か）:
  - **sanitize は純関数**にして、認証やネットワークから完全に切り離す。こうすると
    行データ混入・PII混入・秘密混入といった「漏洩」の判定ロジックだけを
    決定的に単体テストでき、ライブ取得の成否とは独立に安全性を保証できる。
  - **allowlist 方式**（列名＋型だけ通す）にして、Domo応答に将来何が増えても
    既定で落とす。denylist だと新しい漏洩フィールドを取りこぼす。
  - 列が1つも取れなければ **例外**を投げる。空の「偽バックアップ」を書くくらいなら
    何も書かない、というスキルの原則をコードで強制する。

使い方（オフライン・サニタイズ。取得は呼び出し側が curl 等で行い raw JSON を渡す）:
    curl ... > /tmp/raw.json
    python3 scripts/backup_dataset_schema.py \
        --in /tmp/raw.json --name "My Dataset" --source "maintenance-instance:schema/indexed" \
        --out some-app/dataset/my-dataset.schema.json

    # 標準入力からも可（パイプ）:
    curl ... | python3 scripts/backup_dataset_schema.py --in - --name ... --out ...

出力は列の**順序を保持**（スキーマ順は意味を持つため並べ替えない）しつつ、
オブジェクト内キーはソートして差分を安定させる。
"""
from __future__ import annotations

import argparse
import json
import sys
from typing import Any

# 列名として受理するキー（Domoの応答形ごとに揺れる）。
_NAME_KEYS = ("name", "columnName", "column_name")
# 型として受理するキー。
_TYPE_KEYS = ("type", "dataType", "data_type", "columnType")

# 出力に含めてよいトップレベルキー（それ以外は捨てる）。
_ALLOWED_TOP = {"dataset_name", "column_count", "columns", "_note", "_source"}

_NOTE = (
    "Schema-only mirror (column names + types). No row data, previews, owners, "
    "or instance-specific column IDs. Generated by scripts/backup_dataset_schema.py."
)


def _find_columns(raw: Any) -> list[dict]:
    """Domoの複数の応答形から列リストを取り出す。

    対応する形:
      1. {"columns": [ ... ]}                       # schema/indexed（フラット）
      2. {"tables": [{"columns": [ ... ]}, ...]}    # schema/indexed（テーブル入れ子）
      3. {"schema": {"columns": [ ... ]}}           # public API /v1/datasets, AppDB collection
      4. [ {...}, {...} ]                            # 列オブジェクトの素の配列
    見つからなければ ValueError（空の偽バックアップを書かないため）。
    """
    if isinstance(raw, list):
        cols = raw
    elif isinstance(raw, dict):
        if isinstance(raw.get("columns"), list):
            cols = raw["columns"]
        elif isinstance(raw.get("schema"), dict) and isinstance(raw["schema"].get("columns"), list):
            cols = raw["schema"]["columns"]
        elif isinstance(raw.get("tables"), list) and raw["tables"]:
            # 複数テーブルは通常データセットでは想定しないが、先頭テーブルの列を採る。
            first = raw["tables"][0]
            cols = first.get("columns") if isinstance(first, dict) else None
        else:
            cols = None
    else:
        cols = None

    if not isinstance(cols, list) or not cols:
        raise ValueError(
            "スキーマの列が見つからない/空です。取得応答の形が想定外か、権限不足の可能性。"
            "空バックアップは書きません（domo-config-backup スキルの原則）。"
        )
    return cols


def _first(d: dict, keys: tuple[str, ...]) -> Any:
    """dict から keys のうち最初に見つかった非None値を返す。無ければ None。"""
    for k in keys:
        if k in d and d[k] is not None:
            return d[k]
    return None


def sanitize_schema(raw: Any, dataset_name: str, source: str) -> dict:
    """Domoスキーマ応答を、列名＋型だけの安全なミラーに正規化する（純関数）。

    Args:
        raw: Domo API のスキーマ応答（dict または list）。行データが混じっていても、
             ここで列名＋型以外はすべて捨てる。
        dataset_name: 記録用のデータセット表示名（呼び出し側が指定）。
        source: 出所ラベル（例 "maintenance-instance:schema/indexed"）。監査用。

    Returns:
        {"dataset_name", "column_count", "columns":[{"name","type"}], "_note", "_source"}
        の dict。columns は入力順を保持。

    Raises:
        ValueError: 列が取り出せない/空、または列に名前が無い場合。
    """
    cols = _find_columns(raw)
    out_cols: list[dict] = []
    for col in cols:
        if isinstance(col, dict):
            name = _first(col, _NAME_KEYS)
            ctype = _first(col, _TYPE_KEYS)
        elif isinstance(col, str):
            # 文字列だけの列定義（名前のみ）にも一応対応。型は不明。
            name, ctype = col, None
        else:
            # dict でも str でもない列要素は想定外の形。ここで str(col) して name へ
            # 畳み込むと、例えば [["pii@example.com","STRING"]] のような list-of-list が
            # repr 経由で名前欄に丸ごと漏れる（assert_no_leak はキーしか見ないため値の
            # 漏洩は捕まえられない）。このモジュールは allowlist で「想定外は既定で落とす」
            # 設計なので、黙って通さず fail-closed で落とす（NeverEmptyFakeBackup と同じ
            # 「疑わしきは書かない」原則。漏洩防止ツールとして値を素通しさせない）。
            raise ValueError(f"想定外の列要素の型です（dict/str 以外）: {type(col).__name__}")
        # dict 列から取り出した name/type の「値」が dict/list（コンテナ）だと、下の
        # str(name)/str(ctype) が中身を repr で名前欄・型欄へ丸ごと畳み込み、内部の値
        # （PII 等）が漏れる（例 {"name": {"secret": "a@b.com"}} → "{'secret': 'a@b.com'}"）。
        # assert_no_leak はキー集合しか見ないため、この値漏洩は捕まえられない。非 dict/非 str
        # の列「要素」を上で fail-closed にしているのと同じ理由で、値側のコンテナも素通し
        # させない（allowlist「疑わしきは書かない」原則。str/int 等スカラーは str() しても
        # 中身を漏らさないので従来どおり許容する）。
        if isinstance(name, (dict, list)) or isinstance(ctype, (dict, list)):
            raise ValueError("列名/型がスカラーではありません（コンテナ値は repr 経由で値が漏れる恐れ）。")
        if name is None or str(name).strip() == "":
            raise ValueError("列名の無い列があります。スキーマ応答が不正です。")
        out_cols.append({"name": str(name), "type": (str(ctype) if ctype is not None else None)})

    return {
        "dataset_name": str(dataset_name),
        "column_count": len(out_cols),
        "columns": out_cols,
        "_note": _NOTE,
        "_source": str(source),
    }


def assert_no_leak(sanitized: dict) -> None:
    """出力に許可外トップレベルキーが無いことを保証する多重防御。

    sanitize_schema は allowlist で構築するので理論上不要だが、将来の改変で
    漏洩フィールドが紛れ込むのを CI/テストで捕まえるための番犬。
    """
    extra = set(sanitized) - _ALLOWED_TOP
    if extra:
        raise ValueError(f"サニタイズ出力に許可外キー: {sorted(extra)}")
    for col in sanitized.get("columns", []):
        col_extra = set(col) - {"name", "type"}
        if col_extra:
            raise ValueError(f"列に許可外キー: {sorted(col_extra)}")


def dumps(sanitized: dict) -> str:
    """安定した差分になるよう整形（キーはソート、列順は保持、末尾改行）。"""
    assert_no_leak(sanitized)
    return json.dumps(sanitized, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Sanitize a Domo dataset schema into a safe local mirror.")
    ap.add_argument("--in", dest="infile", required=True, help="raw schema JSON path, or '-' for stdin")
    ap.add_argument("--name", required=True, help="dataset display name (for the mirror record)")
    ap.add_argument("--source", required=True, help="provenance label, e.g. 'maintenance-instance:schema/indexed'")
    ap.add_argument("--out", help="output path; if omitted, prints to stdout")
    args = ap.parse_args(argv)

    # 出力側（下の --out 書き込み）は with で確定的に閉じているのに、入力側だけ
    # 素の open().read() だとハンドルが GC 任せになり左右非対称。短命 CLI では実害は
    # 小さいが、consider-using-with（リンタ指摘）と内部の一貫性のため入力側も with で閉じる。
    if args.infile == "-":
        text = sys.stdin.read()
    else:
        with open(args.infile, encoding="utf-8") as fh:
            text = fh.read()
    raw = json.loads(text)
    sanitized = sanitize_schema(raw, args.name, args.source)
    out_text = dumps(sanitized)

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(out_text)
        print(f"wrote {args.out} ({sanitized['column_count']} columns)", file=sys.stderr)
    else:
        sys.stdout.write(out_text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
